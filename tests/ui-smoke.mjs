async function checkResourceErrors(form, label) {
  assert.equal(form.noValidate, true, 'use inline errors instead of native tooltips');
  const name = form.elements.namedItem('name');
  const transmission = form.elements.namedItem('transmission');
  name.focus();
  transmission.focus();
  await tick();
  assert.equal(form.querySelector('[aria-invalid="true"]'), null, 'empty blur stays quiet');
  editInput(name, 'x'.repeat(71));
  await tick();
  assert.equal(name.getAttribute('aria-invalid'), 'false', 'first edit stays quiet');
  name.focus();
  transmission.focus();
  await tick();
  assert.equal(document.activeElement, transmission, 'blur must not steal focus');
  assert.match(document.getElementById(name.getAttribute('aria-describedby')).textContent, /maksimal 70 karakter/);
  editInput(name, ' ');
  await tick();
  assert.match(document.getElementById('f-name-error').textContent, new RegExp(`${label} wajib diisi`));
  transmission.dispatchEvent(new Event('change', { bubbles: true }));
  await tick();
  assert.equal(name.getAttribute('aria-invalid'), 'true', 'another field does not clear this error');
  form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
  await tick();
  assert.equal(document.activeElement, name);
  assert.equal(form.querySelector('#modalError'), null, 'no duplicate form-level validation error');
  editInput(name, 'Nama valid');
  await tick();
  assert.equal(name.getAttribute('aria-invalid'), 'false');
  assert.equal(name.hasAttribute('aria-describedby'), false);
  assert.equal(form.querySelector('[role="alert"]'), null);
}
