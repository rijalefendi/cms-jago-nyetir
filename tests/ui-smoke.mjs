import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><html><head></head><body><div id="root"></div></body></html>', {
  url: 'http://localhost/schools/radja/dashboard/dashboard',
  runScripts: 'dangerously',
  pretendToBeVisual: true,
});
dom.window.scrollTo = () => {};
dom.window.eval(readFileSync('dist/qa.js', 'utf8'));
await new Promise(resolve => setTimeout(resolve, 100));
const { document, Event, MouseEvent } = dom.window;
assert.match(document.getElementById('main').textContent, /Ringkasan/);
assert.equal(document.querySelector('[data-react-page]').dataset.reactPage, 'OverviewPage');
document.querySelector('[data-page="jadwal"]').dispatchEvent(new MouseEvent('click', { bubbles: true }));
assert.equal(document.querySelector('[data-react-page]').dataset.reactPage, 'SchedulePage');
assert.match(dom.window.location.pathname, /\/jadwal$/);
const picker = document.getElementById('schoolPicker');
picker.value = 'demo-b';
picker.dispatchEvent(new Event('change', { bubbles: true }));
assert.equal(document.getElementById('brandWord').textContent, 'Sekolah Mengemudi Contoh');
assert.match(document.getElementById('headerClock').textContent, /WIB/);
assert.match(dom.window.location.pathname, /\/schools\/demo-b\//);
document.querySelector('[data-page="permintaan"]').dispatchEvent(new MouseEvent('click', { bubbles: true }));
document.querySelector('[data-action="add-lead"]').dispatchEvent(new MouseEvent('click', { bubbles: true }));
const leadForm = document.querySelector('form[data-form="add-lead"]');
leadForm.querySelector('[name="name"]').value = 'Peserta Jakarta';
leadForm.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
assert.match(document.getElementById('main').textContent, /Peserta Jakarta/);
picker.value = 'radja';
picker.dispatchEvent(new Event('change', { bubbles: true }));
assert.doesNotMatch(document.getElementById('main').textContent, /Peserta Jakarta/);
document.querySelector('[data-page="instruktur"]').dispatchEvent(new MouseEvent('click', { bubbles: true }));
assert.ok(document.querySelector('[data-action="add-instructor"]'));
assert.ok(document.querySelector('.instructor-table'));
assert.equal(document.querySelectorAll('.instructor-table tbody tr').length, 3);
const instructorSearch = document.getElementById('instructorSearch');
instructorSearch.value = 'instruktur b';
instructorSearch.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(document.querySelectorAll('.instructor-table tbody tr').length, 1);
assert.match(document.querySelector('.instructor-table tbody').textContent, /Instruktur B/);
document.getElementById('instructorSearch').value = '';
document.getElementById('instructorSearch').dispatchEvent(new Event('input', { bubbles: true }));
assert.ok(document.querySelector('[data-action="sort-instructor"][data-sort="name"]'));
assert.ok(document.querySelector('.instructor-table [data-action="delete-instructor"] svg'));
document.querySelector('[data-action="add-instructor"]').click();
let instructorForm = document.querySelector('form[data-form="save-instructor"]');
assert.ok(instructorForm);
instructorForm.querySelector('[name="name"]').value = 'Instruktur Baru';
instructorForm.querySelector('[name="skills"]').value = 'Manual';
instructorForm.querySelector('[name="notes"]').value = 'Catatan uji';
instructorForm.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
assert.match(document.getElementById('main').textContent, /Instruktur Baru/);
let saved = JSON.parse(dom.window.localStorage.getItem('driving-school-demo-v1:radja'));
const created = saved.instructors.find(i => i.name === 'Instruktur Baru');
assert.ok(created);
document.querySelector(`[data-action="edit-instructor"][data-id="${created.id}"]`).click();
instructorForm = document.querySelector('form[data-form="save-instructor"]');
instructorForm.querySelector('[name="name"]').value = 'Instruktur Diperbarui';
instructorForm.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
saved = JSON.parse(dom.window.localStorage.getItem('driving-school-demo-v1:radja'));
assert.equal(saved.instructors.find(i => i.id === created.id).name, 'Instruktur Diperbarui');
document.querySelector('[data-action="edit-instructor"][data-id="I1"]').click();
instructorForm = document.querySelector('form[data-form="save-instructor"]');
instructorForm.querySelector('[name="skills"]').value = 'Matic';
instructorForm.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
assert.match(document.getElementById('modalError').textContent, /Kompetensi/);
assert.equal(JSON.parse(dom.window.localStorage.getItem('driving-school-demo-v1:radja')).instructors.find(i => i.id === 'I1').skills, 'Matic & Manual');
document.querySelector('[data-action="close-modal"]').click();
document.querySelector('[data-action="delete-instructor"][data-id="I1"]').click();
assert.match(document.getElementById('modalRoot').textContent, /sesi/i);
assert.ok(saved.instructors.some(i => i.id === 'I1'));
document.querySelector(`[data-action="delete-instructor"][data-id="${created.id}"]`).click();
document.querySelector(`[data-action="confirm-delete-instructor"][data-id="${created.id}"]`).click();
saved = JSON.parse(dom.window.localStorage.getItem('driving-school-demo-v1:radja'));
assert.ok(!saved.instructors.some(i => i.id === created.id));
console.log('UI smoke passed');
dom.window.close();
